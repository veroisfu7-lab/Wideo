# Озвучка по шотам (Piper, офлайн). Пишет public/vo/<id>.wav и tools/vo_durations.json
import json, subprocess, sys, wave, os
S = sys.argv[1]  # папка с моделью
LINES = [
 ("cold",  "Этой ночью кто-то ходил кругами вокруг его костра. И это был не медведь."),
 ("taboo", "В тайге есть негласный закон: добудешь самку с телёнком — прервёшь целый род. Лес этого не прощает."),
 ("sergey","Сергей промышляет в тайге больше двадцати пяти лет и чтит все правила предков. Но ночью на лабаз может прийти то, к чему не готов ни один охотник."),
 ("offer", "Перед охотой — дань тайге. Хозяину леса оставляют табак и просят: помоги мне в моём деле."),
 ("boil",  "А дальше — маскировка, проверенная веками. Чтобы зверь не почуял чужака за версту, портянки вываривают в хвойном отваре пихты."),
 ("feet",  "Ими обвязывают ноги. В тайге ты обязан раствориться."),
 ("pecker","Шаг делается только под естественный шум леса: стук дятла или порыв ветра."),
 ("labaz", "Вот и лабаз. Впереди — солонец."),
 ("dusk",  "Пока не стемнело, нужно намертво выучить каждый пень. В сумерках глаз обманывает мозг: неподвижная коряга начинает казаться живым зверем."),
 ("night", "Час ночи. Лес словно вымирает. Ни шороха мыши, ни вздоха ветра."),
 ("sound", "И вдруг из чащи доносится странный, ритмичный железный стук. Здесь, в сотне километров от ближайшего жилья."),
 ("under", "А следом — треск веток прямо у основания дерева..."),
 ("fire",  "Оставаться на лабазе — верная ловушка. Приходится спускаться и жечь огонь. Но костёр лишь обозначает тебя, как мишень."),
 ("radar", "Во тьме вокруг поляны начинается движение. Кто-то ходит кругами, проверяя на прочность."),
 ("shot",  "Выстрел в темноту даёт лишь пару минут тишины."),
 ("dawn",  "Тайга отпускает только с рассветом. Звуки растворились в тумане."),
 ("track", "Но у самой кромки леса осталось то, от чего стынет кровь даже у бывалых таёжников..."),
 ("end",   "Что это было на самом деле?"),
]
os.makedirs("public/vo", exist_ok=True); d = {}
for k, t in LINES:
    raw = f"out/vo_{k}_raw.wav"
    subprocess.run([sys.executable, "-m", "piper", "-m", f"{S}/ru_dmitri.onnx", "-f", raw,
                    "--length-scale", "1.08", "--sentence-silence", "0.35"], input=t.encode(), check=True, capture_output=True)
    out = f"public/vo/{k}.wav"
    # голос рассказчика: чуть ниже, плотнее, лёгкая комната
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", raw, "-af",
        "asetrate=22050*0.95,aresample=48000,atempo=1.0526,highpass=f=70,equalizer=f=180:t=q:w=1:g=3,equalizer=f=3500:t=q:w=1.5:g=2,acompressor=threshold=-20dB:ratio=3:attack=5:release=80,aecho=0.8:0.5:35:0.12,loudnorm=I=-16:TP=-1.5",
        "-ar", "48000", "-ac", "1", out], check=True)
    with wave.open(out) as w: d[k] = round(w.getnframes() / w.getframerate(), 2)
    print(k, d[k])
json.dump(d, open("tools/vo_durations.json", "w"), ensure_ascii=False, indent=1)
