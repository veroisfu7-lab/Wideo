# Голова Артёма: нейтральная SDF (глаза — отдельные сферы), волосы отдельным мешем.
# Оси: x вправо (для зрителя — левая щека героя при x>0), y вверх, z вперёд (лицо). Начало — между глаз на уровне зрачков, в глубине черепа.
import sys, numpy as np
from sdflib import *

EYE_R = 0.0122
EYE_C = [V(0.0318, 0.0, 0.0675), V(-0.0318, 0.0, 0.0675)]

def mirror_x(P):
    Q = P.copy(); Q[:, 0] = np.abs(Q[:, 0]); return Q

def lips(P):
    # губы вдоль зубной дуги: цилиндр вокруг вертикали (0, *, 0.047)
    x, y, z = P[:, 0], P[:, 1], P[:, 2]
    zc = 0.047
    th = np.arctan2(x, z - zc); rho = np.sqrt(x * x + (z - zc) ** 2)
    thc = 0.50
    t = np.clip(np.abs(th) / thc, 0, 1)
    taper = np.sqrt(np.clip(np.cos(t * np.pi / 2), 0, 1))
    # верхняя губа: лук Купидона
    yu = -0.0595 + 0.0012 * np.exp(-((th / 0.06) ** 2)) - 0.0035 * t * t
    Ru = 0.0445 - 0.004 * t * t
    du = np.sqrt((rho - Ru) ** 2 / 1.0 + ((y - yu) / 1.1) ** 2) - (0.0052 * taper + 0.0006)
    yl = -0.0705 + 0.0030 * t * t
    Rl = 0.0425 - 0.004 * t * t
    dl = np.sqrt((rho - Rl) ** 2 + ((y - yl) / 1.2) ** 2) - (0.0060 * taper + 0.0006)
    return np.minimum(du, dl), th, rho

def head_sdf(P, with_slit=True, lips_on=True):
    Q = mirror_x(P)
    # череп
    d = ell(P, V(0, 0.03, -0.018), (0.0735, 0.092, 0.097))
    # лоб чуть плоский и широкий
    d = smin(d, ell(P, V(0, 0.045, 0.02), (0.066, 0.058, 0.064)), 0.02)
    # лицевая масса и челюсть
    d = smin(d, ell(P, V(0, -0.035, 0.022), (0.064, 0.074, 0.066)), 0.025)
    d = smin(d, ell(Q, V(0.036, -0.040, 0.046), (0.030, 0.032, 0.030)), 0.02)   # щёки
    d = smin(d, ell(P, V(0, -0.062, 0.050), (0.033, 0.030, 0.038)), 0.02)       # верхняя/нижняя челюсть под губами
    d = smin(d, cap(Q, V(0.058, -0.052, -0.022), V(0.024, -0.104, 0.060), 0.016, 0.013), 0.024)  # линия челюсти
    d = smin(d, ell(P, V(0, -0.100, 0.068), (0.025, 0.019, 0.019)), 0.016)   # подбородок
    # скулы
    d = smin(d, ellR(Q, V(0.050, -0.012, 0.050), (0.022, 0.014, 0.022), rot([0, 1, 0], 0.5)), 0.016)
    # надбровье
    d = smin(d, cap(Q, V(0.006, 0.024, 0.083), V(0.046, 0.026, 0.072), 0.010, 0.008), 0.014)
    # глазницы
    for c in EYE_C:
        d = smax(d, -ell(P, c + V(0, 0.001, 0.007), (0.0165, 0.0105, 0.0105)), 0.005)
    # веки: оболочка вокруг глаза с миндалевидным разрезом
    for c in EYE_C:
        q = P - c
        rr = length(q)
        shell = np.abs(rr - (EYE_R + 0.0016)) - 0.0012
        sx = np.sign(c[0])
        lx = q[:, 0] * sx  # к виску положительно
        phi = np.arctan2(q[:, 1], np.maximum(q[:, 2], 1e-5))
        w = 0.0145
        xx = np.clip((lx + 0.0012) / w, -1.2, 1.2)
        half = 0.38 * np.sqrt(np.clip(1 - xx * xx, 0, 1)) + 0.02
        mid = 0.04 + 0.05 * xx  # внешний уголок чуть выше
        op = (np.abs(phi - mid) - half) * rr
        op = np.where(q[:, 2] > -0.002, op, 0.01)
        lid = smax(shell, -op, 0.0012)
        lid = smax(lid, -(q[:, 2] + 0.001), 0.002)  # только передняя половина
        d = smin(d, lid, 0.004)
    # нос
    d = smin(d, cap(P, V(0, 0.012, 0.083), V(0, -0.028, 0.104), 0.0075, 0.0105), 0.012)
    d = smin(d, sph(P, V(0, -0.030, 0.1055), 0.0115), 0.008)
    d = smin(d, ell(Q, V(0.0125, -0.0355, 0.094), (0.0085, 0.0075, 0.0095)), 0.006)
    d = smax(d, -ell(Q, V(0.0075, -0.0435, 0.0985), (0.0035, 0.0018, 0.0038)), 0.002)  # ноздри
    # губы
    dl, th, rho = lips(P)
    if lips_on: d = smin(d, dl, 0.0045)
    if with_slit and lips_on:
        # щель рта
        slit = np.sqrt(((P[:, 1] + 0.0655 + 0.0022 * (np.clip(np.abs(th) / 0.5, 0, 1)) ** 2) / 0.0011) ** 2 + 0.0) * 0.0011
        slit = np.maximum(slit - 0.0006, np.abs(th) - 0.45)
        slit = np.maximum(slit, -(rho - 0.031))
        d = smax(d, -slit, 0.0012)
    # уши
    for s in (1,):
        eq = ellR(Q, V(0.074, -0.010, -0.010), (0.010, 0.031, 0.019), rot([0, 1, 0], -0.35) @ rot([1, 0, 0], 0.1))
        inner = ellR(Q, V(0.083, -0.008, -0.006), (0.005, 0.021, 0.011), rot([0, 1, 0], -0.35))
        ear = smax(eq, -inner, 0.003)
        d = smin(d, ear, 0.006)
    # шея
    d = smin(d, cap(P, V(0, -0.075, -0.030), V(0, -0.24, -0.045), 0.058, 0.064), 0.03)
    # кадык
    d = smin(d, ell(P, V(0, -0.135, 0.020), (0.010, 0.014, 0.010)), 0.012)
    # обрез шеи снизу
    d = smax(d, -(P[:, 1] + 0.23), 0.01)
    return d

def hair_sdf(P):
    Q = mirror_x(P)
    base = ell(P, V(0, 0.034, -0.019), (0.0805, 0.1005, 0.105))
    # объём сверху (текстурный кроп)
    base = smin(base, ell(P, V(0, 0.085, 0.0), (0.066, 0.042, 0.088)), 0.03)
    # линия роста по углу вокруг вертикали: 0 — лоб, pi/2 — над ухом, pi — затылок
    y = P[:, 1]; z = P[:, 2]
    ang = np.abs(np.arctan2(P[:, 0], P[:, 2] + 0.01))
    ylim = np.interp(ang, [0.0, 0.55, 0.95, 1.3, 1.65, 2.1, 2.6, 3.2], [0.066, 0.060, 0.036, 0.020, 0.024, -0.010, -0.050, -0.066]).astype(f32)
    d = smax(base, ylim - y, 0.008)
    # пряди: гребни вдоль направления «вперёд-вниз»
    n1 = np.sin(P[:, 0] * 300 + 2.0 * np.sin(z * 60) + fbm(P, 30, 2, 3) * 4) * 0.0010
    n2 = fbm(P, 45, 3, 5) * 0.0026
    d = d + n1 + n2
    # пара прядей на лоб
    d = smin(d, cap(P, V(0.012, 0.095, 0.06), V(0.026, 0.060, 0.092), 0.007, 0.0035), 0.008)
    d = smin(d, cap(P, V(-0.01, 0.098, 0.055), V(-0.002, 0.066, 0.094), 0.006, 0.003), 0.008)
    # только снаружи кожи: волосы — оболочка, без внутренних поверхностей (иначе тень на лицо)
    d = smax(d, -(head_sdf(P, with_slit=False) - 0.0015), 0.002)
    return d

